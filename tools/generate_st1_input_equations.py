"""Generate scalar ST1 input arithmetic from its authoritative CML annotations.

Only the flat CML operand/operator grammar is accepted. Operand reads, sign
application, product reduction and summation retain the expression evaluator's
order, including its explicit zero terms. Run with --check in validation.
"""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'ipss.plugin.core/src/main/java/org/interpss/dstab/control/exc/ieee/y1981/st1'


def generate():
    plan_source = (PACKAGE / 'St1DirectEvaluation.java').read_text()
    names = re.findall(r'"(\w+)"', re.search(
        r'static final String\[\] NAMES\s*=\s*\{([^}]+)\}', plan_source).group(1))
    assert len(names) == len(set(names)) == 8, 'Unexpected ST1 slot layout'
    source = (PACKAGE / 'IEEE1981ST1Exciter.java').read_text()
    source = re.sub(r'/\*.*?\*/|//[^\n]*', '', source, flags=re.S)
    annotations = dict((name, body) for body, name in re.findall(
        r'@AnControllerField\((.*?)\)\s*(?:public\s+)?\w+\s+(\w+)', source, re.S))
    equations = []
    types = {'mach.vt': 'MachVt', 'pss.vs': 'PssVs', 'this.refPoint': 'ControllerRefPoint'}
    for name in names:
        expression = re.search(r'\binput\s*=\s*"([^"]+)"', annotations[name]).group(1)
        text = re.sub(r'\s+', '', expression)
        parts = re.findall(r'([+*/-]?)([A-Za-z_]\w*(?:\.\w+)*)', text)
        assert ''.join(op + symbol for op, symbol in parts) == text, expression
        equations.append([(op or '+', symbol) for op, symbol in parts])

    lines = ['package org.interpss.dstab.control.exc.ieee.y1981.st1;', '',
             'import com.interpss.dstab.datatype.ExpCalculator;',
             'import com.interpss.dstab.datatype.CMLVarEnum;', '',
             '/** Generated by tools/generate_st1_input_equations.py; edit the model annotations. */',
             'final class St1InputEquations {', '    private St1InputEquations() {}',
             '    static boolean matches(int id, ExpCalculator expression) {',
             '        var records = expression.getRecList();', '        return switch (id) {']
    operators = {'+': 'Add', '-': 'Sub', '*': 'Mul', '/': 'Div'}
    for slot, terms in enumerate(equations):
        checks = [f'records.length == {len(terms)}']
        for i, (op, symbol) in enumerate(terms):
            kind = types.get(symbol, 'ControllerFieldOutput' if symbol.endswith('.y') else 'ControllerFieldParameter')
            checks.extend([f'records[{i}].opt == ExpCalculator.Opt.{operators[op]}',
                           f'records[{i}].getSymbolType() == CMLVarEnum.{kind}',
                           f'"{symbol}".equals(records[{i}].getSymbolStr())'])
        lines.append(f'            case {slot} -> ' + '\n                && '.join(checks) + ';')
    lines += ['            default -> false;', '        };', '    }', '',
              '    static double evaluate(St1DirectEvaluation plan, int id) {',
              '        var model = plan.model;', '        switch (id) {']
    for slot, terms in enumerate(equations):
        lines.append(f'        case {slot}: {{')
        for i, (_, symbol) in enumerate(terms):
            if symbol == 'mach.vt': reader = 'plan.voltage()'
            elif symbol == 'pss.vs': reader = 'plan.pss()'
            elif symbol == 'this.refPoint': reader = 'model.getRefPoint()'
            elif symbol == 'this.uelGate1Function.y': reader = 'plan.gate()'
            elif symbol.endswith('.y'): reader = f'plan.y({names.index(symbol.split(".")[1])})'
            else:
                assert symbol.startswith('this.') and symbol.count('.') == 1, symbol
                reader = 'model.' + symbol[5:]
            lines.append(f'            double v{i} = {reader};')
        for i, (op, _) in enumerate(terms):
            if op == '-': lines.append(f'            v{i} = -v{i};')
        for i, (op, _) in enumerate(terms):
            if op in ('*', '/'):
                assert i > 0
                lines += [f'            v{i} = v{i-1} {op} v{i};', f'            v{i-1} = 0.;']
        lines.append('            double sum = 0.;')
        lines += [f'            sum += v{i};' for i in range(len(terms))]
        lines += ['            return sum;', '        }']
    lines += ['        default: throw new IllegalArgumentException("Unknown ST1 input slot");',
              '        }', '    }', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = PACKAGE / 'St1InputEquations.java'
    expected = generate()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit('ST1 generated input equations are stale')
    else:
        output.write_text(expected, encoding='utf-8')
